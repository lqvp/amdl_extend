async def test_start_waits_until_regions_are_reported(fake_launcher, tmp_path):
    sup = _supervisor(fake_launcher, tmp_path)
    await sup.start()
    try:
        assert sup.running
        assert sup.bound_port > 0
        assert (await sup.status())["regions"] == ["jp"]
    finally:
        await sup.stop()


async def test_readiness_waits_for_status_not_for_the_banner(fake_launcher_slow, tmp_path):
    # the launcher prints its banner long before it actually serves
    sup = _supervisor(fake_launcher_slow, tmp_path, startup_timeout=30.0)
    started = time.monotonic()
    await sup.start()
    try:
        assert time.monotonic() - started >= 1.0, "start() returned before the port served"
        assert (await sup.status())["regions"] == ["jp"]
    finally:
        await sup.stop()


