# How long a test waits for a stub to serve /status. Generous for a deliberately slow
# stub, short enough that a stuck test fails in seconds rather than minutes.
EXTERNAL_READY_TIMEOUT = 15.0

# One template with a mode substituted in, rather than six scripts: the parts the
# supervisor actually depends on -- the argv spelling, the banner, the envelope shape,
# serving until SIGTERM -- are then identical across the six, so a difference in a test's
# outcome is a difference in the mode and not in the scaffolding.
_STUB_SOURCE = '''\
#!{python}
"""Stub wrapper-lite launcher (mode={mode!r}). Generated by tests/test_supervisor.py."""
import json
import os
import signal
import socket
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

MODE = {mode!r}
SLOW_SECONDS = {slow_seconds!r}
# Set by the /status handler in "crash_after_ready" mode, so the stub dies *because* it was
# asked whether it was up -- the only version of this that cannot race the readiness poll. A
# timer would have to outlast an unknown startup cost to guarantee `start()` saw the 200
# first, which is a flaky test on a loaded machine.
CRASH_AFTER_FIRST_STATUS = threading.Event()
# Written by "crash_once" the first time it is asked whether it is up, and read by the
# respawned copy, so exactly one crash happens per directory. `tmp_path` is per-test, so
# this cannot leak between tests.
CRASH_ONCE_MARKER = Path(".crash_once_done")
# The one socket option the real payload's listener sets (httplib.h:2047-2049), kept so a
# second bind on the same port is not refused by a TIME_WAIT remnant.
SO_REUSEPORT = getattr(socket, "SO_REUSEPORT", 0)


class _Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def do_GET(self):  # noqa: N802 - the name BaseHTTPRequestHandler requires
        if self.path == "/status":
            body = json.dumps(
                {{"code": 0, "msg": "SUCCESS", "data": {{"regions": {regions!r}}}}}
            ).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            if MODE == "crash_after_ready":
                # The response is already on the wire, so the supervisor's probe succeeds
                # and `start()` returns; the exit happens after. Dicts are ordered here.
                CRASH_AFTER_FIRST_STATUS.set()
            if MODE == "crash_once":
                # Crashes on its first /status and never again, because the marker file it
                # leaves behind is what the respawned copy reads. Self-contained: the test
                # asserts a stable wrapper comes back without having to arrange anything.
                if not CRASH_ONCE_MARKER.exists():
                    CRASH_ONCE_MARKER.write_text("")
                    CRASH_AFTER_FIRST_STATUS.set()
        else:
            self.send_error(404)

    def log_message(self, fmt, *args):
        # A request log line, not a suppressed one: the real payload logs every request,
        # and a stub that only ever logs during startup cannot tell a live pump from a
        # dead one. `test_a_raising_log_sink_does_not_kill_the_pump` depends on it.
        sys.stdout.write("2026-09-27 00:00:00.000 [INFO ] " + (fmt % args) + "\\n")
        sys.stdout.flush()


def _arg(name, default=None):
    argv = sys.argv[1:]
    for i, arg in enumerate(argv):
        if arg == name:
            return argv[i + 1]
    return default


def _listen_port():
    port = _arg("--port")
    if port is None:
        sys.exit("stub launcher in service mode requires an explicit --port")
    return int(port)


def _isolate():
    """Put this process in its own session, so a group signal cannot reach the test runner.

    Universal, not just for the R7 stub, and that is the point. A `killpg` in `stop()` aimed
    at a stub that shares the runner's process group hits the runner: the whole suite dies
    with exit 143 and reports nothing. That is a catch by catastrophe, not a test, and it
    stops the mutant from being *diagnosed* -- the run just vanishes.

    The real launcher isolates far more aggressively (`unshare(CLONE_NEWUSER|CLONE_NEWNS|
    CLONE_NEWPID)`), so this is also the more faithful stub. With every stub in its own
    session, a group-signal mutant can only ever show up as a failed assertion.
    """
    try:
        os.setsid()
    except PermissionError:  # already a group leader; the group is ours alone anyway
        pass


def _spawn_grandchild():
    """Start a process in this session that a pid signal to us will not reach.

    This is the R7 trap made observable. The launcher `unshare`s `CLONE_NEWPID`, so the
    payload `lite` is PID 1 of a nested PID namespace: a signal aimed at "the process group"
    from the supervisor does not mean what it appears to, and against the real binary it
    would not reach the payload at all.

    With the stub in its own session (see `_isolate`) the grandchild is in a group that
    contains the stub and nothing else. A signal to the child pid takes the stub and leaves
    the grandchild; a signal to the child's process group takes both. The first is correct
    and the second is the bug, so the grandchild's survival is the assertion.

    Its output goes to DEVNULL so it does not hold this process's stdout pipe open after the
    supervisor is killed -- otherwise the log pump would never see EOF.
    """
    grandchild = subprocess.Popen(
        [
            sys.executable,
            "-c",
            "import time; time.sleep(600)  # stub_grandchild: reaped by the test",
        ],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    print("stub_grandchild pid: " + str(grandchild.pid), flush=True)


def _install_sigterm():
    # The real payload consumes SIGTERM via sigwait and shuts down gracefully
    # (lite_main.cpp:447; the spike recorded returncode=0), so exiting 0 here is what
    # makes `test_stop_terminates_the_child` a test of the supervisor's signalling rather
    # than a test of this stub. Main thread only -- `signal.signal` raises elsewhere, and
    # "crash_after_ready" serves on a worker.
    signal.signal(signal.SIGTERM, lambda *_: sys.exit(0))


def _serve_forever(port):
    class _Server(ThreadingHTTPServer):
        allow_reuse_address = True

        def server_bind(self):
            if SO_REUSEPORT:
                self.socket.setsockopt(socket.SOL_SOCKET, SO_REUSEPORT, 1)
            super().server_bind()

    server = _Server(("127.0.0.1", port), _Handler)
    try:
        server.serve_forever(poll_interval=0.05)
    except KeyboardInterrupt:
        pass


def _chroot():
    """Model the launcher's chroot, so a base dir of "data" means `./rootfs/data`.

    `wrapper-lite-rootless.c` chdirs into `./rootfs` and chroots into it, then resolves
    `--base-dir` inside that tree, so the payload's `<base-dir>/2fa.txt` is a *host* path
    under the binary's own `rootfs/`. Modelled here because that is the mapping the
    supervisor has to reproduce on the host side to create the file at all.
    """
    base = Path("rootfs") / _arg("--base-dir", "data")
    base.mkdir(parents=True, exist_ok=True)
    return base


def _login():
    """The payload's `--login` mode, as `lite_main.cpp:538-600` behaves.

    Credentials off argv, never stdin. Then, because a spawned child has a pipe (not a tty)
    on fd 0, `auth.cpp:64`'s isatty branch cannot fire and the code comes from a file: log
    the hint, poll for it, read it, remove it. That is the real path. A stub that read the
    code from a pipe would test a channel the binary does not have, which is the mistake
    this mode exists to prevent.
    """
    creds = _arg("--login")
    if creds is None or ":" not in creds:
        print("invalid login format, expected user:pass", flush=True)
        return 1
    user = creds.split(":", 1)[0]
    # Echoed, because a child that echoes what it was handed is the case that leaks a
    # password into a log pane.
    print("2026-09-27 00:00:00.000 [INFO ] wrapper-lite login mode", flush=True)
    print("login received: " + creds, flush=True)
    needs_2fa = MODE != "login_no_2fa"
    print(
        "2026-09-27 00:00:01.000 [INFO ] credentialHandler: "
        + "{{title: , message: , 2FA: "
        + ("true" if needs_2fa else "false")
        + "}}",
        flush=True,
    )
    if not needs_2fa:
        # The account needs no code: cache the tokens and exit, which is the common real
        # outcome and the one that must not make the caller wait out a prompt timeout.
        print("2026-09-27 00:00:01.000 [INFO ] login complete, exiting", flush=True)
        return 0
    code_path = _chroot() / "2fa.txt"
    print(
        "2026-09-27 00:00:01.000 [WARN ] Enter your 2FA code into "
        + _arg("--base-dir", "data")
        + "/2fa.txt",
        flush=True,
    )

    # Polled, then removed, exactly like auth.cpp:84-99. A test that only wrote the file and
    # never checked the child consumed it would pass against a supervisor that wrote the
    # wrong path, so the consumption is the assertion that matters here.
    for _ in range({twofa_poll_tries}):
        if code_path.exists():
            code = code_path.read_text().strip()
            # The mode is reported so the owner-only assertion can be made from the only
            # side that can see it: this is a separate process, and by the time the parent
            # looks the file is already gone.
            mode = oct(code_path.stat().st_mode & 0o777)
            code_path.unlink()
            print("Code file detected! Logging in...", flush=True)
            print(
                "2FA code " + code + " accepted for " + user + " (mode " + mode + ")",
                flush=True,
            )
            print("2026-09-27 00:00:02.000 [INFO ] login complete, exiting", flush=True)
            return 0
        time.sleep({twofa_poll_seconds})
    print("2FA code timeout, aborting login", flush=True)
    return 1


def _main():
    _install_sigterm()
    _isolate()

    if MODE in ("login_2fa", "login_no_2fa"):
        # A login child is a separate, short-lived process that never listens -- see
        # `login()`'s docstring. So this mode does the handshake and exits, which is also
        # what makes `submit_2fa`'s "the login child is gone" branch reachable.
        sys.exit(_login())

    port = _listen_port()

    if MODE == "crash":
        # What a launcher that died in namespace setup looks like: one perror() line and
        # exit 1 (wrapper-lite-rootless.c:121 and neighbours). No banner, and no
        # "initializing" -- that line comes from the payload, which never got to run.
        print("mkdir ./rootfs/proc failed: Operation not permitted", flush=True)
        sys.exit(1)

    print("2026-09-27 00:00:00.000 [INFO ] initializing...", flush=True)
    print("2026-09-27 00:00:00.000 [INFO ] initializing ctx...", flush=True)

    # Every mode reaches the banner. In "slow" and "hang" it is a lie, which is the
    # point: the real launcher prints this line 6-19 s before svr.listen() succeeds.
    print(
        "2026-09-27 00:00:00.000 [INFO ] wrapper-lite listening on 127.0.0.1:"
        + str(port),
        flush=True,
    )

    if MODE == "banner_then_exit":
        sys.exit(0)
    if MODE == "hang":
        while True:
            time.sleep(0.2)
    if MODE == "slow":
        time.sleep(SLOW_SECONDS)

    print("2026-09-27 00:00:00.000 [INFO ] service ready", flush=True)

    if MODE == "setsid":
        _spawn_grandchild()
        _serve_forever(port)
        return

    if MODE in ("crash_after_ready", "crash_once"):
        # Becomes ready, then dies the moment anybody checks. This is the watcher's path:
        # a child that answers /status and then goes away is what a restart has to handle.
        # Serving happens on a worker so the main thread is free to die on demand; `sys.exit`
        # there ends the process, which is the point.
        threading.Thread(
            target=_serve_forever, args=(port,), daemon=True
        ).start()
        CRASH_AFTER_FIRST_STATUS.wait()
        print("2026-09-27 00:00:01.000 [ERROR ] simulated crash after ready", flush=True)
        sys.exit(7)

    _serve_forever(port)


if __name__ == "__main__":
    _main()
'''


def _stub(
    directory: Path,
    mode: str,
    *,
    slow_seconds: float = 1.5,
    twofa_poll_tries: int = 200,
    twofa_poll_seconds: float = 0.05,
    regions: list | None = None,
) -> Path:
    """Materialise one stub launcher and return its path.

    The shebang is `sys.executable` rather than a bare `python3` on purpose: this host's
    system python3 is 3.14.7 and the venv is 3.13.7, and a stub running under a different
    interpreter than the tests would make any failure ambiguous.

    The 2FA poll is `tries x seconds` rather than the payload's `20 x 3s`: the shape is what
    the test needs to pin -- that the supervisor writes a file the child finds and removes,
    inside a window the TTL has to fit inside -- and 60 real seconds would make the suite
    unusable. The TTL-vs-window relationship is asserted separately against the constant.
    """
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"stub_{mode}"
    path.write_text(
        _STUB_SOURCE.format(
            python=sys.executable,
            mode=mode,
            slow_seconds=slow_seconds,
            twofa_poll_tries=twofa_poll_tries,
            twofa_poll_seconds=twofa_poll_seconds,
            regions=["jp"] if regions is None else regions,
        ),
        encoding="utf-8",
    )
    path.chmod(0o755)
    return path


