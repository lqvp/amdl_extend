async def test_a_crashed_wrapper_is_restarted(fake_launcher_crash_once, tmp_path):
    """A wrapper that dies *after* serving comes back on its own.

    An unexpected exit is a restart with exponential backoff. This is the case
    round one did not implement -- the watcher reaped and reported but never respawned.

    **The observable is the supervisor's own "serving again" line, not a new pid.** Those are
    not the same moment, and the difference is a race: `_restart_after_crash` calls
    `_ensure_child()`, which spawns and sets `pid`, and only *then* awaits `_wait_ready()`
    (`wrapper_supervisor.py:1029-1030`). A poll that breaks on "the pid changed" therefore
    returns while the new child is still in `bind()`, and the HTTP GET below lands on a port
    that is not listening yet. Measured: 0 failures in isolation, 20 of 20 under 2x CPU
    oversubscription, failing with `ConnectError('All connection attempts failed')`.

    So the test waits for the line the supervisor emits *after* readiness (`:1034`), which is
    the supervisor's own definition of a successful restart -- "serving again", not "spawned
    again". `test_the_restart_budget_stops_the_loop` polls a log line for the same reason.
    """
    lines: list[str] = []
    sup = _supervisor(
        fake_launcher_crash_once, tmp_path, log_sink=lines.append, max_restarts=3
    )
    try:
        await sup.start()
        first = sup.pid
        assert first is not None
        for _ in range(200):
            if any("is serving again on" in line for line in lines):
                break
            await asyncio.sleep(0.05)
        assert any("is serving again on" in line for line in lines), (
            "the wrapper never reported serving again\n" + "\n".join(lines)
        )
        assert sup.running, "\n".join(lines)
        assert sup.pid != first, "the wrapper was never respawned"
        assert any("restarting the wrapper in" in line for line in lines), lines
        # And the respawned one is genuinely serving, not merely alive.
        assert (await sup.status())["regions"] == ["jp"]
    finally:
        await sup.stop()


