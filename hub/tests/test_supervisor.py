async def test_a_second_login_does_not_inherit_the_first_logins_code(
    fake_launcher_2fa_slow_poll, tmp_path
):
    """The review's reproduction, as a test.

    Log in, hand over a code, stop before the child polls it, then log in again with a
    different account. Without the cleanup the second login finds the first login's file,
    consumes it, and reports `2FA code 111111 accepted for user2` -- a code nobody typed for
    that account, appended to its password by `auth.cpp:92-96`.
    """
    lines: list[str] = []
    path = tmp_path / "rootfs" / "data" / "2fa.txt"
    sup = _supervisor(fake_launcher_2fa_slow_poll, tmp_path, log_sink=lines.append)
    first = await sup.login("user1", "pass1")
    await sup.submit_2fa(first.id, "111111")
    await sup.stop()
    assert not path.exists(), "the first login's code survived stop()"

    try:
        second = await sup.login("user2", "pass2")
        await asyncio.sleep(0.3)
        # The claim: nothing was consumed until *this* login was given a code. Codes and
        # account names are both redacted, so the assertion is positional -- the single
        # detection has to come after the second login's own prompt.
        assert not _detections(lines), lines
        assert len(_prompts(lines)) == 2, lines

        await sup.submit_2fa(second.id, "222222")
        for _ in range(400):
            if _detections(lines):
                break
            await asyncio.sleep(0.05)
        assert len(_detections(lines)) == 1, lines
        assert _detections(lines)[0] > _prompts(lines)[-1], lines
        assert sum("accepted for" in line for line in lines) == 1, lines
    finally:
        await sup.stop()
    assert not path.exists()


