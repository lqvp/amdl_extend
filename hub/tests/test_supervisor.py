def _free_port() -> int:
    """An ephemeral port nothing is listening on.

    The supervisor does the same for `port=0` (see `_pick_ephemeral_port`), and that is
    inherently racy between closing the socket and the child binding. The window is not
    observable here because the stub -- like the real payload -- sets `SO_REUSEPORT`.
    """
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


_EXTERNAL: list[asyncio.subprocess.Process] = []


async def _start_external_wrapper(binary: Path) -> int:
    """Start a healthy wrapper on a port of its own, and return that port.

    Deliberately *not* a `WrapperSupervisor`: the point is a wrapper the supervisor did
    not start, which is the only shape the adoption path can encounter.
    """
    port = _free_port()
    proc = await asyncio.create_subprocess_exec(
        str(binary),
        "--base-dir",
        "data",
        "--host",
        "127.0.0.1",
        "--port",
        str(port),
        stdin=asyncio.subprocess.DEVNULL,
        stdout=asyncio.subprocess.DEVNULL,
        stderr=asyncio.subprocess.STDOUT,
    )
    _EXTERNAL.append(proc)

    deadline = time.monotonic() + EXTERNAL_READY_TIMEOUT
    async with httpx.AsyncClient(timeout=1.0) as client:
        while time.monotonic() < deadline:
            if proc.returncode is not None:
                raise RuntimeError(
                    f"the external stub exited with {proc.returncode} before serving"
                )
            try:
                response = await client.get(f"http://127.0.0.1:{port}/status")
            except httpx.HTTPError:
                response = None
            if response is not None and response.status_code == 200:
                return port
            await asyncio.sleep(0.05)
    raise RuntimeError("the external stub never served /status")


async def _stop_external_wrapper() -> None:
    while _EXTERNAL:
        proc = _EXTERNAL.pop()
        if proc.returncode is None:
            proc.terminate()
        await proc.wait()


def _stub_pids() -> dict[int, str]:
    """Every live process whose command line mentions a stub launcher.

    Linux-only by construction, and the fallback on any read error is to ignore the pid
    rather than fail the suite: this is a safety net, not the assertion.
    """
    found: dict[int, str] = {}
    for entry in os.listdir("/proc"):
        if not entry.isdigit():
            continue
        try:
            with open(f"/proc/{entry}/cmdline", "rb") as handle:
                cmdline = handle.read().decode("utf-8", "replace")
        except OSError:
            continue
        if "stub_" in cmdline:
            found[int(entry)] = cmdline
    return found


@pytest.fixture(autouse=True)
async def _no_leaked_children(tmp_path: Path):
    """Reap what a test left behind -- processes *and* files -- and say so.

    A stray stub holds its port for the rest of the session, which would turn one broken
    assertion into a cascade of unrelated ones. A stray `2fa.txt` is worse in kind: the
    payload consumes it unconditionally, so it becomes the next login's password
    (`auth.cpp:92-96`). Both are checked here rather than trusted to each test's `finally`,
    because both were observed leaking.
    """
    before = set(_stub_pids())
    yield
    await _stop_external_wrapper()
    leaked = {pid: cmdline for pid, cmdline in _stub_pids().items() if pid not in before}
    for pid in leaked:
        try:
            os.kill(pid, signal.SIGKILL)
        except OSError:
            pass
    assert not leaked, f"the test leaked stub launcher processes: {sorted(leaked)}"

    stale = sorted(
        str(path)
        for pattern in ("2fa.txt", ".2fa.txt.*")
        for path in tmp_path.rglob(pattern)
        if path.is_file()
    )
    for name in stale:
        with contextlib.suppress(OSError):
            Path(name).unlink()
    assert not stale, f"the test left 2FA files behind: {stale}"


def _supervisor(binary: Path, tmp_path: Path, **kwargs) -> WrapperSupervisor:
    """A supervisor on an ephemeral port, because these tests must not collide with the
    wrapper already on 127.0.0.1:12340 on this host.

    `base_dir` is `Path("data")`, not `tmp_path`, and that is not laziness. The launcher
    resolves `--base-dir` *after* `chroot(".")` into its own `rootfs/`, so the payload's
    `2fa.txt` is a host path of `<binary dir>/rootfs/data/2fa.txt`. Passing an absolute
    `tmp_path` would put the supervisor and the stub in different trees and the 2FA tests
    would pass for the wrong reason -- the stub would find a file nobody wrote to.
    """
    return WrapperSupervisor(
        binary=binary,
        base_dir=kwargs.pop("base_dir", Path("data")),
        host="127.0.0.1",
        port=kwargs.pop("port", 0),
        log_sink=kwargs.pop("log_sink", lambda _: None),
        **kwargs,
    )


